function getLocaleContent(locale) {
  return serviceCatalog[locale] ?? serviceCatalog.en;
}

export function getServiceList(locale) {
  return getLocaleContent(locale);
}

export function getServiceBySlug(locale, slug) {
  const localizedService =
    getLocaleContent(locale).find((service) => service.slug === slug) ?? null;

  if (localizedService) {
    return localizedService;
  }

  return serviceCatalog.en.find((service) => service.slug === slug) ?? null;
}
